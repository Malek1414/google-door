#!/usr/bin/env python3
"""Regression: does data/berlin-mitte.json still agree with OSM about Hauptbahnhof?

The fixture is generated by pipeline/make_fixture.py from live OSM. This test checks
the built dataset against it. Run after every pipeline change.
"""
import json, math, sys

D = json.load(open("data/berlin-mitte.json"))
F = json.load(open("pipeline/fixtures/hbf_groundtruth.json"))
by_id = {e["id"]: e for e in D["entrances"]}
s, w, n, e = F["bbox"]
inbox = [x for x in D["entrances"] if s <= x["lat"] <= n and w <= x["lon"] <= e]

def hav(a, b):
    R = 6371000
    p1, p2 = math.radians(a[0]), math.radians(b[0])
    dp, dl = p2 - p1, math.radians(b[1] - a[1])
    h = math.sin(dp/2)**2 + math.cos(p1)*math.cos(p2)*math.sin(dl/2)**2
    return 2 * R * math.asin(math.sqrt(h))

fails = []
def check(name, got, want):
    ok = got == want
    print(f"  {'PASS' if ok else 'FAIL'}  {name}: got {got}, want {want}")
    if not ok: fails.append(name)

print("Hauptbahnhof regression")
c = F["counts"]
check("entrances in bbox", len(inbox), c["entrances"])
check("stepFree true",  sum(1 for x in inbox if x["stepFree"] is True),  c["stepFreeTrue"])
check("stepFree false", sum(1 for x in inbox if x["stepFree"] is False), c["stepFreeFalse"])
check("stepFree null",  sum(1 for x in inbox if x["stepFree"] is None),  c["stepFreeNull"])

p = F["closest_contradiction"]
a, b = by_id.get(p["stepFree"]["id"]), by_id.get(p["notStepFree"]["id"])
if not a or not b:
    print("  FAIL  contradiction pair missing from dataset"); fails.append("pair present")
else:
    check("pair — step-free door",     a["stepFree"], True)
    check("pair — inaccessible door",  b["stepFree"], False)
    d = hav((a["lat"], a["lon"]), (b["lat"], b["lon"]))
    ok = abs(d - p["separationM"]) <= p["toleranceM"]
    print(f"  {'PASS' if ok else 'FAIL'}  pair separation: {d:.1f} m, "
          f"want {p['separationM']} +/-{p['toleranceM']}")
    if not ok: fails.append("separation")

r = by_id.get(F["revolving"]["id"])
if not r:
    print("  FAIL  revolving-door node missing"); fails.append("revolving present")
else:
    check("Europaplatz stepFree", r["stepFree"], True)
    check("Europaplatz door",     r["door"], "revolving")
    check("Europaplatz warned",   "revolving" in (r["warnings"] or []), True)

# tier discipline: nothing above tier 1 may ever carry usable coords
bad = [x["id"] for x in D["entrances"] if x["tier"] != 1 and x["stepFree"] is not None]
print(f"  {'PASS' if not bad else 'FAIL'}  tier discipline: "
      f"{len(bad)} entries with a verdict but tier != 1")
if bad: fails.append("tier discipline")

print(f"\n{'ALL PASS' if not fails else str(len(fails)) + ' FAILED: ' + ', '.join(fails)}")
sys.exit(1 if fails else 0)
